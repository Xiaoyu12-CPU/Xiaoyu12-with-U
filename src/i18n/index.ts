const LANGUAGE_TAGS: Record<AppLanguage, string> = {
  "zh-CN": "zh-CN",
  en: "en-US",
  ja: "ja-JP",
};

export const LANGUAGE_OPTIONS: readonly { value: AppLanguage; label: string }[] = [
  { value: "zh-CN", label: "中文" },
  { value: "en", label: "English" },
  { value: "ja", label: "日本語" },
];

export const currentLanguage = computed(
  () => settingsManager.settings.value.general.language,
);

export const currentLocaleTag = computed(
  () => LANGUAGE_TAGS[currentLanguage.value],
);

export function translate(
  key: TranslationKey,
  parameters: Readonly<Record<string, string | number>> = {},
): string {
  return translateForLanguage(currentLanguage.value, key, parameters);
}

export function translateForLanguage(
  language: AppLanguage,
  key: TranslationKey,
  parameters: Readonly<Record<string, string | number>> = {},
): string {
  const template = language === "zh-CN"
    ? key
    : language === "ja"
      ? JA_MESSAGES[key]
      : EN_MESSAGES[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(parameters, name)
      ? String(parameters[name])
      : match);
}

export function setLanguage(language: AppLanguage): void {
  settingsManager.updateSetting("general", "language", language);
}

export const i18nPlugin = {
  install(app: App): void {
    app.config.globalProperties.$t = translate;
    watchEffect(() => {
      document.documentElement.lang = currentLocaleTag.value;
    });
  },
};

declare module "vue" {
  interface ComponentCustomProperties {
    $t: typeof translate;
  }
}
